/* 目標レベルマスタ */
CREATE TABLE IF NOT EXISTS goal_levels (
	id INT PRIMARY KEY
  , level_code VARCHAR(20) NOT NULL UNIQUE
  , display_order INT NOT NULL
  , enabled BOOLEAN NOT NULL DEFAULT TRUE
);

/* ユーザーマスタ */
CREATE TABLE IF NOT EXISTS users (
	user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , e164_phone_number VARCHAR(16) NOT NULL UNIQUE
  , user_name VARCHAR(50)
  , password VARCHAR(100)
  , goal_level_id INT
  , lesson_minutes INT NOT NULL DEFAULT 60
  , role VARCHAR(50)
  , created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  , updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  
  , CONSTRAINT fk_users_goal_level
  		FOREIGN KEY (goal_level_id)
  		REFERENCES goal_levels(id)
  
  , CONSTRAINT chk_users_lesson_minutes
  		CHECK (lesson_minutes > 0 AND MOD(lesson_minutes, 30) = 0)
);

/* 予約マスタ */
CREATE TABLE IF NOT EXISTS reservations (
	reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  , user_id BIGINT NOT NULL
  , starts_at TIMESTAMP NOT NULL
  , ends_at TIMESTAMP NOT NULL
  , status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED'
  , version BIGINT NOT NULL DEFAULT 0
  , created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  , updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  , created_by BIGINT
  , updated_by BIGINT
  
  , CONSTRAINT fk_reservations_user
  		FOREIGN KEY (user_id)
  		REFERENCES users(user_id)
  
  , CONSTRAINT chk_reservations_time
  		CHECK (ends_at > starts_at)
  		
  , CONSTRAINT fk_reservations_created_by
  		FOREIGN KEY (created_by)
  		REFERENCES users(user_id)
  		ON DELETE SET NULL
  		
  , CONSTRAINT fk_reservations_updated_by
  		FOREIGN KEY (updated_by)
  		REFERENCES users(user_id)
  		ON DELETE SET NULL
);

/* 予約可能時間 */
CREATE TABLE IF NOT EXISTS lesson_openings (
	opening_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
	/* 	RDS MySQLに作成する場合は
		opening_id BIGINT AUTO_INCREMENT PRIMARY KEY 
	*/
  , starts_at TIMESTAMP NOT NULL
  , ends_at TIMESTAMP NOT NULL
  
  , CONSTRAINT chk_lesson_openings_time
  		CHECK (ends_at > starts_at)
);

/* 予約登録時の排他制御用 */
CREATE TABLE IF NOT EXISTS reservation_lock (
	lock_id INT PRIMARY KEY
);

/* 予約の時間帯設定 */
CREATE TABLE IF NOT EXISTS reservation_settings (
	settings_id INT PRIMARY KEY
  , selectable_start_time TIME NOT NULL
  , selectable_end_time TIME NOT NULL
  
  , CONSTRAINT chk_reservation_settings_id
  		CHECK (settings_id = 1)
  	
  , CONSTRAINT chk_reservation_settings_time
  		CHECK (selectable_start_time < selectable_end_time)
);